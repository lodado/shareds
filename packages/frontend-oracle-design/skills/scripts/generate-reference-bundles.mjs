#!/usr/bin/env node
// Generate pre-joined reference bundles from reference-graph.json.
//
// Why this exists: a lane reads the same node set in the same order on every run, but reading them
// as N separate tool calls produces a different prompt prefix each time and loses the cache. A
// bundle is the identical bytes joined in one deterministic order, so a repeat session reads one
// file and hits the cache. It never adds, edits, or summarizes reference content — a bundle that
// drifts from its nodes is a generation defect, and `--check` fails on it.

import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const skillDirectory = join(dirname(fileURLToPath(import.meta.url)), '..')
const graphPath = join(skillDirectory, 'references/reference-graph.json')
const bundleDirectory = join(skillDirectory, 'bundles')

const GENERATED_NOTICE =
  'Generated by scripts/generate-reference-bundles.mjs — do not edit. Edit the source reference nodes and regenerate.'

export async function loadGraph() {
  return JSON.parse(await readFile(graphPath, 'utf8'))
}

function resolveNodes(graph, bundle) {
  const byId = new Map(graph.nodes.map((node) => [node.id, node]))
  const seen = new Set()
  const resolved = []

  const visit = (id, trail) => {
    if (trail.includes(id)) throw new Error(`bundle ${bundle.id} has a requires cycle at ${id}`)
    const node = byId.get(id)
    if (!node) throw new Error(`bundle ${bundle.id} references unknown node ${id}`)
    for (const dependency of node.requires) visit(dependency, [...trail, id])
    if (seen.has(id)) return
    seen.add(id)
    resolved.push(node)
  }

  for (const id of bundle.nodes) visit(id, [])
  return resolved
}

export async function renderBundle(graph, bundle) {
  const nodes = resolveNodes(graph, bundle)
  const sections = await Promise.all(
    nodes.map(async (node) => {
      const body = await readFile(join(skillDirectory, node.path), 'utf8')
      return `<!-- node:${node.id} path:${node.path} -->\n\n${body.trimEnd()}\n`
    }),
  )

  const header = [
    `# Bundle — ${bundle.id}`,
    '',
    `> ${GENERATED_NOTICE}`,
    '',
    `- When: ${bundle.when}`,
    `- Nodes: ${nodes.map((node) => node.id).join(', ')}`,
    '',
    'Reading this bundle counts as reading every node listed above. Report those node ids in the',
    'lane header, not the bundle id — the header states what was actually read, and a bundle is a',
    'delivery mechanism for the same bytes, not a node of its own.',
    '',
  ].join('\n')

  return `${header}\n${sections.join('\n')}`
}

export function bundlePath(bundle) {
  return join(bundleDirectory, `${bundle.id}.md`)
}

async function main() {
  const check = process.argv.includes('--check')
  const graph = await loadGraph()
  const bundles = graph.bundles ?? []
  if (bundles.length === 0) throw new Error('reference-graph.json declares no bundles')

  const expected = new Map()
  for (const bundle of bundles) expected.set(`${bundle.id}.md`, await renderBundle(graph, bundle))

  if (check) {
    const present = new Set(
      (await readdir(bundleDirectory, { withFileTypes: true }).catch(() => []))
        .filter((entry) => entry.isFile())
        .map((entry) => entry.name),
    )
    const problems = []
    for (const [name, content] of expected) {
      const actual = await readFile(join(bundleDirectory, name), 'utf8').catch(() => null)
      if (actual === null) problems.push(`${name} is missing`)
      else if (actual !== content) problems.push(`${name} is stale`)
    }
    for (const name of present) if (!expected.has(name)) problems.push(`${name} is not declared in reference-graph.json`)

    if (problems.length > 0) {
      console.error(`BUNDLE_DRIFT\n${problems.map((problem) => `- ${problem}`).join('\n')}`)
      console.error('Run: pnpm --filter @lodado/frontend-oracle-design-plugin bundles:generate')
      process.exitCode = 1
      return
    }
    console.log(`bundles ok — ${expected.size} bundles match their nodes`)
    return
  }

  await rm(bundleDirectory, { recursive: true, force: true })
  await mkdir(bundleDirectory, { recursive: true })
  for (const [name, content] of expected) await writeFile(join(bundleDirectory, name), content, 'utf8')
  console.log(`generated ${expected.size} bundles in bundles/`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main()
}
